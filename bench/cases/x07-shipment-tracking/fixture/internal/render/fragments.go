package render

import (
	"strings"
)

// Page is one HTML document: the service's shell around a body this package rendered. The title and the
// subtitle are escaped; the body is markup this package produced, so it is written as it is. The signed
// footer names the build so an operator can tell two deployments apart.
func Page(title, subtitle, body string) string {
	var b strings.Builder
	b.WriteString("<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n")
	b.WriteString("<title>")
	b.WriteString(Escape(title))
	b.WriteString(" · shiptrack</title>\n")
	b.WriteString("<style>")
	b.WriteString(shellCSS)
	b.WriteString("</style>\n</head>\n<body>\n")
	b.WriteString(`<header class="top"><strong>shiptrack</strong>`)
	if subtitle != "" {
		b.WriteString(`<span class="sub">`)
		b.WriteString(Escape(subtitle))
		b.WriteString(`</span>`)
	}
	b.WriteString("</header>\n<main>\n")
	b.WriteString(`<h1>`)
	b.WriteString(Escape(title))
	b.WriteString("</h1>\n")
	b.WriteString(body)
	b.WriteString("\n</main>\n<footer>Generated by shiptrack. Amounts are in minor units of EUR unless a line says otherwise.</footer>\n</body>\n</html>\n")
	return b.String()
}

// Breadcrumb renders a trail of names, each escaped, with the last one marked as the current page.
func Breadcrumb(names []string) string {
	if len(names) == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteString(`<nav class="crumbs">`)
	for i, name := range names {
		if i > 0 {
			b.WriteString(`<span class="sep">/</span>`)
		}
		if i == len(names)-1 {
			b.WriteString(`<span aria-current="page">`)
			b.WriteString(Escape(name))
			b.WriteString(`</span>`)
			continue
		}
		b.WriteString(Escape(name))
	}
	b.WriteString(`</nav>`)
	return b.String()
}

// Section renders a heading and a body this package produced. The heading is escaped; the body is
// markup from another function of this package.
func Section(heading, body string) string {
	var b strings.Builder
	b.WriteString(`<section><h2>`)
	b.WriteString(Escape(heading))
	b.WriteString(`</h2>`)
	b.WriteString(body)
	b.WriteString(`</section>`)
	return b.String()
}

// SectionID renders a section with a stable id derived from the heading, so a link to it survives a
// reordering of the page. The id is a class-shaped value and never the heading itself.
func SectionID(heading, body string) string {
	var b strings.Builder
	b.WriteString(`<section id="`)
	b.WriteString(Class(Escape(heading)))
	b.WriteString(`"><h2>`)
	b.WriteString(Escape(heading))
	b.WriteString(`</h2>`)
	b.WriteString(body)
	b.WriteString(`</section>`)
	return b.String()
}

